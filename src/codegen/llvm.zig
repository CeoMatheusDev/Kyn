//! LLVM IR backend (text).
//!
//! Emits textual IR for the current subset: `i32`/`void` functions, `i32`/`bool`
//! variables, arithmetic, comparisons, `&&`/`||` with short-circuit,
//! `if`/`else`, `while` and direct function calls.
//!
//! Structs: struct values only exist in local variables (no parameters,
//! returns, pointers or struct fields), so each field gets its own
//! `alloca` — scalar replacement of a struct that never escapes. That
//! removes aggregate types and `getelementptr` without changing observable
//!
//! `str` is a slice (pointer + length): in variables it takes two `alloca`s
//! (`ptr` and `i64`); in calls it becomes two parameters (`ptr` + `i64`) and
//! the return uses the aggregate `{ ptr, i64 }` with `insertvalue`/`extractvalue`.
//!
//! This emitter is not validated by an LLVM assembler in the development
//! environment (no `llc`/`clang` available); the tests check the structure of
//! the emitted text. For end-to-end executable validation see the
//! `x86_64_asm` backend, which is assembled and linked with `as`/`ld`.

const std = @import("std");
const ast = @import("../ast/ast.zig");
const sema = @import("../sema/sema.zig");
const codegen = @import("codegen.zig");

pub const Error = codegen.Error;

pub fn emit(
    arena: std.mem.Allocator,
    program: *const ast.Program,
    checked: *const sema.Checked,
) Error![]const u8 {
    var out: std.ArrayList(u8) = .empty;
    var state = codegen.ProgramState{ .strs = codegen.StrPool.init(arena) };
    try out.print(arena, "; LLVM IR generated by kync (bootstrap)\n", .{});
    try out.print(arena, "target triple = \"x86_64-unknown-linux-gnu\"\n\n", .{});

    for (program.functions, 0..) |func, i| {
        var emitter = FnEmitter.init(arena, func, checked, checked.functions[i], &state);
        try emitter.emitFunction();
        try emitter.serialize(&out);
        try out.append(arena, '\n');
    }

    // `print`/`print_i32` use the libc `write`: the IR declares the symbol and each
    // string becomes a private byte-list constant (no escapes).
    const needs_write = state.strs.texts.items.len > 0 or state.used_print or state.used_print_i32;
    if (needs_write) {
        try out.print(arena, "declare i64 @write(i32, ptr, i64)\n\n", .{});
    }

    // Decimal formatting: internal function emitted once per module.
    if (state.used_print_i32) {
        try out.appendSlice(arena, kyn_print_i32_ir);
    }

    if (state.strs.texts.items.len > 0 or state.used_print or state.used_print_i32) {
        for (state.strs.texts.items, 0..) |text, index| {
            if (text.len == 0) {
                try out.print(arena, "@.str{d} = private unnamed_addr constant [0 x i8] zeroinitializer, align 1\n", .{index});
                continue;
            }
            try out.print(arena, "@.str{d} = private unnamed_addr constant [{d} x i8] [", .{ index, text.len });
            for (text, 0..) |byte, byte_index| {
                if (byte_index != 0) try out.print(arena, ", ", .{});
                try out.print(arena, "i8 {d}", .{byte});
            }
            try out.print(arena, "], align 1\n", .{});
        }
        if (state.used_print or state.used_print_i32) {
            try out.print(arena, "@.nl = private unnamed_addr constant [1 x i8] [i8 10], align 1\n", .{});
        }
    }

    return out.toOwnedSlice(arena);
}

fn llvmType(typ: sema.Type) codegen.Error![]const u8 {
    return switch (typ) {
        .i32 => "i32",
        .bool => "i1",
        .void => "void",
        // A struct in LLVM is represented field by field (scalar replacement).
        .aggregate => error.UnsupportedType,
        // An enum is tag + payload slots, never a single operand.
        .enumeration => error.UnsupportedType,
        // `str` is pointer + length: represented by two slots.
        .str => error.UnsupportedType,
        .unknown => error.UnsupportedType,
    };
}

/// Return type of a function: `str` comes back as a `{ ptr, i64 }` pair and an
/// enum as `{ i32, i32 }` (tag, payload).
fn llvmReturnType(typ: sema.Type) codegen.Error![]const u8 {
    return switch (typ) {
        .str => "{ ptr, i64 }",
        .enumeration => "{ i32, i32 }",
        else => llvmType(typ),
    };
}

fn typeAlign(typ: sema.Type) codegen.Error!u32 {
    return switch (typ) {
        .i32 => 4,
        .bool => 1,
        .void => error.UnsupportedType,
        .aggregate => error.UnsupportedType,
        .enumeration => error.UnsupportedType,
        .str => error.UnsupportedType,
        .unknown => error.UnsupportedType,
    };
}

const Operand = struct {
    text: []const u8,
    typ: sema.Type,
};

/// Call site of an expression: a free call (`list` = written arguments) or a
/// method call (`receiver` = `base`). `null` for anything else — including an
/// enum constructor, which is not a call.
const CallRef = struct { index: u32, site: codegen.Arguments };

fn callRefOf(expr: *ast.Expr) codegen.Error!?CallRef {
    return switch (expr.kind) {
        .call => |call| .{
            .index = call.callee_fn orelse return error.MiscompiledAst,
            .site = .{ .list = call.args },
        },
        .method_call => |call| if (call.resolved_fn) |index| .{
            .index = index,
            .site = .{ .receiver = call.base, .list = call.args },
        } else null,
        else => null,
    };
}

const Block = struct {
    label: []const u8,
    body: std.ArrayList(u8) = .empty,
    terminated: bool = false,
};

const FnEmitter = struct {
    arena: std.mem.Allocator,
    func: *const ast.Function,
    checked: *const sema.Checked,
    info: sema.FunctionInfo,
    /// Shared program state (string pool and `print` usage).
    state: *codegen.ProgramState,

    blocks: std.ArrayList(Block) = .empty,
    current: usize = 0,
    tmp_count: u32 = 0,
    label_count: u32 = 0,

    fn init(
        arena: std.mem.Allocator,
        func: *const ast.Function,
        checked: *const sema.Checked,
        info: sema.FunctionInfo,
        state: *codegen.ProgramState,
    ) FnEmitter {
        return .{ .arena = arena, .func = func, .checked = checked, .info = info, .state = state };
    }

    fn block(self: *FnEmitter) *Block {
        return &self.blocks.items[self.current];
    }

    fn startBlock(self: *FnEmitter, label: []const u8) !void {
        try self.blocks.append(self.arena, .{ .label = label });
        self.current = self.blocks.items.len - 1;
    }

    fn emit(self: *FnEmitter, comptime fmt: []const u8, args: anytype) !void {
        const b = self.block();
        if (b.terminated) return;
        try b.body.print(self.arena, fmt, args);
    }

    fn br(self: *FnEmitter, label: []const u8) !void {
        if (self.block().terminated) return;
        try self.emit("  br label %{s}\n", .{label});
        self.block().terminated = true;
    }

    fn condBr(self: *FnEmitter, cond: []const u8, then_label: []const u8, else_label: []const u8) !void {
        if (self.block().terminated) return;
        try self.emit("  br i1 {s}, label %{s}, label %{s}\n", .{ cond, then_label, else_label });
        self.block().terminated = true;
    }

    fn retVoid(self: *FnEmitter) !void {
        if (self.block().terminated) return;
        try self.emit("  ret void\n", .{});
        self.block().terminated = true;
    }

    fn newTemp(self: *FnEmitter) ![]const u8 {
        const name = try std.fmt.allocPrint(self.arena, "%t{d}", .{self.tmp_count});
        self.tmp_count += 1;
        return name;
    }

    fn newLabel(self: *FnEmitter, prefix: []const u8) ![]const u8 {
        const name = try std.fmt.allocPrint(self.arena, "{s}{d}", .{ prefix, self.label_count });
        self.label_count += 1;
        return name;
    }

    fn varName(self: *FnEmitter, slot: u32) ![]const u8 {
        return std.fmt.allocPrint(self.arena, "%v{d}", .{slot});
    }

    fn symbolAt(self: *FnEmitter, index: u32) *const sema.Symbol {
        return &self.checked.symbols[index];
    }

    fn structFields(self: *FnEmitter, struct_id: u32) Error![]const sema.FieldInfo {
        if (struct_id >= self.checked.structs.len) return error.MiscompiledAst;
        return self.checked.structs[struct_id].fields;
    }

    /// IR aggregate type for a struct: `{ i32, i1, ... }`, in declaration
    /// order. Used only in returns — parameters are flattened into scalar
    /// values, as in the native backend.
    fn structType(self: *FnEmitter, struct_id: u32) Error![]const u8 {
        const fields = try self.structFields(struct_id);
        var text: std.ArrayList(u8) = .empty;
        try text.appendSlice(self.arena, "{ ");
        for (fields, 0..) |field, i| {
            if (i != 0) try text.appendSlice(self.arena, ", ");
            try text.appendSlice(self.arena, try llvmType(field.typ));
        }
        try text.appendSlice(self.arena, " }");
        return text.items;
    }

    fn returnType(self: *FnEmitter, typ: sema.Type, struct_id: u32) Error![]const u8 {
        if (typ == .aggregate) return self.structType(struct_id);
        return llvmReturnType(typ);
    }

    /// Field-by-field values of a struct expression, already in SSA:
    /// literal (each field evaluated), variable (`load` per field) or call
    /// returning a struct (`extractvalue` per field).
    fn structFieldValues(self: *FnEmitter, expr: *ast.Expr, struct_id: u32) Error![][]const u8 {
        const fields = try self.structFields(struct_id);
        const values = try self.arena.alloc([]const u8, fields.len);

        switch (expr.kind) {
            .struct_literal => |lit| {
                for (fields, 0..) |field, i| {
                    const init_value = findFieldInit(lit.fields, field.name) orelse return error.MiscompiledAst;
                    const operand = try self.emitExpr(init_value);
                    if (operand.typ == .void) return error.UnsupportedNode;
                    values[i] = operand.text;
                }
            },
            .identifier => {
                const src = self.symbolAt(expr.resolved orelse return error.MiscompiledAst);
                if (src.typ != .aggregate) return error.MiscompiledAst;
                for (fields, 0..) |field, i| {
                    const ty = try llvmType(field.typ);
                    const align_value = try typeAlign(field.typ);
                    const name = try self.varName(src.slot + 1 + @as(u32, @intCast(i)));
                    const tmp = try self.newTemp();
                    try self.emit("  {s} = load {s}, ptr {s}, align {d}\n", .{ tmp, ty, name, align_value });
                    values[i] = tmp;
                }
            },
            .call, .method_call => {
                const ref = (try callRefOf(expr)) orelse return error.MiscompiledAst;
                const aggregate = try self.emitStructCall(ref.index, ref.site);
                const aggregate_type = try self.structType(struct_id);
                for (fields, 0..) |_, i| {
                    const tmp = try self.newTemp();
                    try self.emit("  {s} = extractvalue {s} {s}, {d}\n", .{ tmp, aggregate_type, aggregate, i });
                    values[i] = tmp;
                }
            },
            else => return error.MiscompiledAst,
        }

        return values;
    }

    /// Call whose return is a struct: returns the temporary holding the aggregate.
    fn emitStructCall(self: *FnEmitter, fn_index: u32, site: codegen.Arguments) Error![]const u8 {
        const callee = self.checked.functions[fn_index];
        if (callee.return_type != .aggregate) return error.MiscompiledAst;
        const args = try self.emitArgs(site, callee.params, callee.param_struct_ids);
        const aggregate_type = try self.structType(callee.return_struct_id);
        const result = try self.newTemp();
        try self.emit("  {s} = call {s} @{s}({s})\n", .{ result, aggregate_type, callee.symbol_name, args });
        return result;
    }

    fn emitFunction(self: *FnEmitter) !void {
        try self.startBlock("entry");

        // All slots allocated at once, in the entry block.
        const sym_start: usize = self.info.symbol_start;
        const sym_end: usize = sym_start + self.info.symbol_count;
        for (self.checked.symbols[sym_start..sym_end]) |sym| {
            if (sym.typ == .str) {
                // Pointer in the base slot and length in the following slot.
                try self.emit("  {s} = alloca ptr, align 8\n", .{try self.varName(sym.slot)});
                try self.emit("  {s} = alloca i64, align 8\n", .{try self.varName(sym.slot + 1)});
                continue;
            }
            if (sym.typ == .enumeration) {
                // Tag in the base slot, payload in the next one (same mapping
                // as the native backend); the payload slot stays unused when
                // no case declares a payload.
                try self.emit("  {s} = alloca i32, align 4\n", .{try self.varName(sym.slot)});
                try self.emit("  {s} = alloca i32, align 4\n", .{try self.varName(sym.slot + 1)});
                continue;
            }
            if (sym.typ == .aggregate) {
                if (sym.struct_id >= self.checked.structs.len) return error.MiscompiledAst;
                for (self.checked.structs[sym.struct_id].fields, 0..) |field, i| {
                    const ty = try llvmType(field.typ);
                    const align_value = try typeAlign(field.typ);
                    const name = try self.varName(sym.slot + 1 + @as(u32, @intCast(i)));
                    try self.emit("  {s} = alloca {s}, align {d}\n", .{ name, ty, align_value });
                }
                continue;
            }
            const ty = try llvmType(sym.typ);
            const align_value = try typeAlign(sym.typ);
            const name = try self.varName(sym.slot);
            try self.emit("  {s} = alloca {s}, align {d}\n", .{ name, ty, align_value });
        }

        // Parameters are copied into their slots (str: two arguments).
        var arg_index: usize = 0;
        for (self.func.params, 0..) |_, i| {
            const sym = &self.checked.symbols[sym_start + i];
            if (sym.typ == .aggregate) {
                const fields = try self.structFields(sym.struct_id);
                for (fields, 0..) |field, field_index| {
                    const ty = try llvmType(field.typ);
                    const align_value = try typeAlign(field.typ);
                    const name = try self.varName(sym.slot + 1 + @as(u32, @intCast(field_index)));
                    try self.emit("  store {s} %arg{d}, ptr {s}, align {d}\n", .{ ty, arg_index, name, align_value });
                    arg_index += 1;
                }
                continue;
            }
            if (sym.typ == .str) {
                try self.emit("  store ptr %arg{d}, ptr {s}, align 8\n", .{ arg_index, try self.varName(sym.slot) });
                try self.emit("  store i64 %arg{d}, ptr {s}, align 8\n", .{ arg_index + 1, try self.varName(sym.slot + 1) });
                arg_index += 2;
            } else if (sym.typ == .enumeration) {
                try self.emit("  store i32 %arg{d}, ptr {s}, align 4\n", .{ arg_index, try self.varName(sym.slot) });
                try self.emit("  store i32 %arg{d}, ptr {s}, align 4\n", .{ arg_index + 1, try self.varName(sym.slot + 1) });
                arg_index += 2;
            } else {
                const ty = try llvmType(sym.typ);
                const align_value = try typeAlign(sym.typ);
                try self.emit("  store {s} %arg{d}, ptr {s}, align {d}\n", .{ ty, arg_index, try self.varName(sym.slot), align_value });
                arg_index += 1;
            }
        }

        try self.emitStatements(self.func.body);

        if (!self.block().terminated) {
            if (self.info.return_type == .void) {
                try self.retVoid();
            } else {
                // Semantics guarantees `return` on every path; this
                // terminator is only a structural safeguard for the IR.
                try self.emit("  unreachable\n", .{});
                self.block().terminated = true;
            }
        }

        // Every basic block must end with `ret`, `br` or `unreachable`.
        // Blocks only reached by conditional branches (for instance
        // `if_end` when both branches return) are closed here.
        for (self.blocks.items) |*b| {
            if (b.terminated) continue;
            try b.body.appendSlice(self.arena, "  unreachable\n");
            b.terminated = true;
        }
    }

    fn serialize(self: *FnEmitter, out: *std.ArrayList(u8)) !void {
        var signature: std.ArrayList(u8) = .empty;
        var arg_index: usize = 0;
        for (self.func.params, 0..) |_, i| {
            const param_type = self.info.params[i];
            const struct_id = if (i < self.info.param_struct_ids.len) self.info.param_struct_ids[i] else 0;
            if (param_type == .aggregate) {
                // Struct: one argument per field, in declaration order.
                const fields = try self.structFields(struct_id);
                for (fields) |field| {
                    if (arg_index != 0) try signature.appendSlice(self.arena, ", ");
                    try signature.print(self.arena, "{s} %arg{d}", .{ try llvmType(field.typ), arg_index });
                    arg_index += 1;
                }
                continue;
            }
            if (arg_index != 0) try signature.appendSlice(self.arena, ", ");
            if (param_type == .str) {
                // Slice: pointer and length take two arguments.
                try signature.print(self.arena, "ptr %arg{d}, i64 %arg{d}", .{ arg_index, arg_index + 1 });
                arg_index += 2;
            } else if (param_type == .enumeration) {
                // Enum: tag and payload take two arguments.
                try signature.print(self.arena, "i32 %arg{d}, i32 %arg{d}", .{ arg_index, arg_index + 1 });
                arg_index += 2;
            } else {
                try signature.print(self.arena, "{s} %arg{d}", .{ try llvmType(param_type), arg_index });
                arg_index += 1;
            }
        }

        const ret_type = try self.returnType(self.info.return_type, self.info.return_struct_id);
        try out.print(self.arena, "define {s} @{s}({s}) {{\n", .{ ret_type, self.info.symbol_name, signature.items });

        for (self.blocks.items) |*b| {
            try out.print(self.arena, "{s}:\n", .{b.label});
            try appendIndented(out, self.arena, b.body.items);
        }
        try out.appendSlice(self.arena, "}\n");
    }

    fn emitStatements(self: *FnEmitter, stmts: []*ast.Stmt) Error!void {
        for (stmts) |stmt| {
            if (self.block().terminated) return;
            try self.emitStatement(stmt);
        }
    }

    fn emitStatement(self: *FnEmitter, stmt: *ast.Stmt) Error!void {
        switch (stmt.kind) {
            .let_decl => |decl| {
                const symbol = self.symbolAt(stmt.decl_symbol orelse return error.MiscompiledAst);
                if (symbol.typ == .aggregate) {
                    try self.emitStructStore(symbol, decl.init);
                    return;
                }
                if (symbol.typ == .str) {
                    try self.emitStrStore(symbol, decl.init);
                    return;
                }
                if (symbol.typ == .enumeration) {
                    try self.emitEnumStore(symbol, decl.init);
                    return;
                }
                const value = try self.emitExpr(decl.init);
                if (value.typ == .void) return error.UnsupportedNode;
                const ty = try llvmType(symbol.typ);
                const align_value = try typeAlign(symbol.typ);
                const name = try self.varName(symbol.slot);
                try self.emit("  store {s} {s}, ptr {s}, align {d}\n", .{ ty, value.text, name, align_value });
            },

            .assign => |assign| {
                const symbol = self.symbolAt(assign.resolved orelse return error.MiscompiledAst);
                if (symbol.typ == .aggregate) {
                    try self.emitStructStore(symbol, assign.value);
                    return;
                }
                if (symbol.typ == .str) {
                    try self.emitStrStore(symbol, assign.value);
                    return;
                }
                if (symbol.typ == .enumeration) {
                    try self.emitEnumStore(symbol, assign.value);
                    return;
                }
                const value = try self.emitExpr(assign.value);
                if (value.typ == .void) return error.UnsupportedNode;
                const ty = try llvmType(symbol.typ);
                const align_value = try typeAlign(symbol.typ);
                const name = try self.varName(symbol.slot);
                try self.emit("  store {s} {s}, ptr {s}, align {d}\n", .{ ty, value.text, name, align_value });
            },

            .field_assign => |field_assign| {
                const base = self.symbolAt(field_assign.base.resolved orelse return error.MiscompiledAst);
                if (base.typ != .aggregate) return error.MiscompiledAst;
                const field_index = field_assign.field_index orelse return error.MiscompiledAst;
                if (base.struct_id >= self.checked.structs.len) return error.MiscompiledAst;
                const field = &self.checked.structs[base.struct_id].fields[field_index];

                const value = try self.emitExpr(field_assign.value);
                if (value.typ == .void) return error.UnsupportedNode;
                const ty = try llvmType(field.typ);
                const align_value = try typeAlign(field.typ);
                const name = try self.varName(base.slot + 1 + field_index);
                try self.emit("  store {s} {s}, ptr {s}, align {d}\n", .{ ty, value.text, name, align_value });
            },

            .return_stmt => |maybe_expr| {
                if (self.info.return_type == .void) {
                    try self.retVoid();
                } else if (self.info.return_type == .str) {
                    const expr = maybe_expr orelse return error.MiscompiledAst;
                    const value = try self.strOperand(expr);
                    const with_ptr = try self.newTemp();
                    try self.emit("  {s} = insertvalue {{ ptr, i64 }} undef, ptr {s}, 0\n", .{ with_ptr, value.ptr });
                    const with_len = try self.newTemp();
                    try self.emit("  {s} = insertvalue {{ ptr, i64 }} {s}, i64 {s}, 1\n", .{ with_len, with_ptr, value.len });
                    try self.emit("  ret {{ ptr, i64 }} {s}\n", .{with_len});
                    self.block().terminated = true;
                } else if (self.info.return_type == .enumeration) {
                    const expr = maybe_expr orelse return error.MiscompiledAst;
                    // A call returning an enum already is the aggregate.
                    if (expr.kind == .call or expr.kind == .method_call) {
                        const ref = (try callRefOf(expr)) orelse return error.MiscompiledAst;
                        const direct = try self.emitEnumCall(ref.index, ref.site);
                        try self.emit("  ret {{ i32, i32 }} {s}\n", .{direct});
                        self.block().terminated = true;
                        return;
                    }
                    const value = try self.enumOperand(expr);
                    const with_tag = try self.newTemp();
                    try self.emit("  {s} = insertvalue {{ i32, i32 }} undef, i32 {s}, 0\n", .{ with_tag, value.tag });
                    const with_payload = try self.newTemp();
                    try self.emit("  {s} = insertvalue {{ i32, i32 }} {s}, i32 {s}, 1\n", .{ with_payload, with_tag, value.payload });
                    try self.emit("  ret {{ i32, i32 }} {s}\n", .{with_payload});
                    self.block().terminated = true;
                } else if (self.info.return_type == .aggregate) {
                    const expr = maybe_expr orelse return error.MiscompiledAst;
                    const aggregate_type = try self.structType(self.info.return_struct_id);
                    // A call returning a struct already is the aggregate: return it directly.
                    if (expr.kind == .call or expr.kind == .method_call) {
                        const ref = (try callRefOf(expr)) orelse return error.MiscompiledAst;
                        const direct = try self.emitStructCall(ref.index, ref.site);
                        try self.emit("  ret {s} {s}\n", .{ aggregate_type, direct });
                        self.block().terminated = true;
                        return;
                    }
                    const fields = try self.structFields(self.info.return_struct_id);
                    const values = try self.structFieldValues(expr, self.info.return_struct_id);
                    var current: []const u8 = "undef";
                    var current_type: []const u8 = aggregate_type;
                    for (fields, 0..) |field, i| {
                        const ty = try llvmType(field.typ);
                        const next = try self.newTemp();
                        try self.emit("  {s} = insertvalue {s} {s}, {s} {s}, {d}\n", .{ next, current_type, current, ty, values[i], i });
                        current = next;
                        current_type = aggregate_type;
                    }
                    try self.emit("  ret {s} {s}\n", .{ aggregate_type, current });
                    self.block().terminated = true;
                } else {
                    const expr = maybe_expr orelse return error.MiscompiledAst;
                    const value = try self.emitExpr(expr);
                    const ty = try llvmType(self.info.return_type);
                    try self.emit("  ret {s} {s}\n", .{ ty, value.text });
                    self.block().terminated = true;
                }
            },

            .expr_stmt => |expr| {
                _ = try self.emitExpr(expr);
            },

            .if_stmt => |if_stmt| {
                const cond = try self.emitExpr(if_stmt.cond);
                const then_label = try self.newLabel("if_then");
                const else_label = try self.newLabel("if_else");
                const end_label = try self.newLabel("if_end");
                try self.condBr(cond.text, then_label, else_label);

                try self.startBlock(then_label);
                try self.emitStatements(if_stmt.then_body);
                try self.br(end_label);

                try self.startBlock(else_label);
                if (if_stmt.else_body) |else_branch| {
                    switch (else_branch) {
                        .block => |stmts| try self.emitStatements(stmts),
                        .if_stmt => |nested| try self.emitStatement(nested),
                    }
                }
                try self.br(end_label);

                try self.startBlock(end_label);
            },

            .while_stmt => |while_stmt| {
                const cond_label = try self.newLabel("while_cond");
                const body_label = try self.newLabel("while_body");
                const end_label = try self.newLabel("while_end");

                try self.br(cond_label);
                try self.startBlock(cond_label);
                const cond = try self.emitExpr(while_stmt.cond);
                try self.condBr(cond.text, body_label, end_label);

                try self.startBlock(body_label);
                try self.emitStatements(while_stmt.body);
                try self.br(cond_label);

                try self.startBlock(end_label);
            },

            .switch_stmt => |*sw| try self.emitSwitch(sw),

            .block => |stmts| try self.emitStatements(stmts),
        }
    }

    /// Tag constant of an enum case.
    fn caseTag(self: *FnEmitter, enum_id: u32, case_index: u32) Error![]const u8 {
        if (enum_id >= self.checked.enums.len) return error.MiscompiledAst;
        const info = &self.checked.enums[enum_id];
        if (case_index >= info.cases.len) return error.MiscompiledAst;
        return std.fmt.allocPrint(self.arena, "{d}", .{info.cases[case_index].tag});
    }

    /// Writes an enum value (tag + optional payload) into the two slots of
    /// `dst`: a case without payload, a constructor with payload, or a copy of
    /// another enum variable.
    /// Tag and payload of an enum value, already in SSA: case without payload
    /// (`0`), constructor (payload evaluated), variable (`load` per slot) or
    /// call returning an enum (`extractvalue` per field).
    const EnumOperand = struct { tag: []const u8, payload: []const u8 };

    fn enumOperand(self: *FnEmitter, expr: *ast.Expr) Error!EnumOperand {
        switch (expr.kind) {
            .field_access => |access| {
                return .{
                    .tag = try self.caseTag(
                        access.resolved_enum orelse return error.MiscompiledAst,
                        access.resolved_case orelse return error.MiscompiledAst,
                    ),
                    .payload = "0",
                };
            },
            .method_call => |call| {
                // A method returning an enum already yields the aggregate.
                if (call.resolved_fn) |index| {
                    const aggregate = try self.emitEnumCall(index, .{ .receiver = call.base, .list = call.args });
                    const tag = try self.newTemp();
                    try self.emit("  {s} = extractvalue {{ i32, i32 }} {s}, 0\n", .{ tag, aggregate });
                    const payload = try self.newTemp();
                    try self.emit("  {s} = extractvalue {{ i32, i32 }} {s}, 1\n", .{ payload, aggregate });
                    return .{ .tag = tag, .payload = payload };
                }
                const tag = try self.caseTag(
                    call.resolved_enum orelse return error.MiscompiledAst,
                    call.resolved_case orelse return error.MiscompiledAst,
                );
                if (call.args.len != 1) return error.MiscompiledAst;
                const payload = try self.emitExpr(call.args[0]);
                if (payload.typ != .i32) return error.UnsupportedNode;
                return .{ .tag = tag, .payload = payload.text };
            },
            .identifier => {
                const src = self.symbolAt(expr.resolved orelse return error.MiscompiledAst);
                if (src.typ != .enumeration) return error.MiscompiledAst;
                const tag = try self.newTemp();
                try self.emit("  {s} = load i32, ptr {s}, align 4\n", .{ tag, try self.varName(src.slot) });
                const payload = try self.newTemp();
                try self.emit("  {s} = load i32, ptr {s}, align 4\n", .{ payload, try self.varName(src.slot + 1) });
                return .{ .tag = tag, .payload = payload };
            },
            .call => {
                const ref = (try callRefOf(expr)) orelse return error.MiscompiledAst;
                const aggregate = try self.emitEnumCall(ref.index, ref.site);
                const tag = try self.newTemp();
                try self.emit("  {s} = extractvalue {{ i32, i32 }} {s}, 0\n", .{ tag, aggregate });
                const payload = try self.newTemp();
                try self.emit("  {s} = extractvalue {{ i32, i32 }} {s}, 1\n", .{ payload, aggregate });
                return .{ .tag = tag, .payload = payload };
            },
            else => return error.MiscompiledAst,
        }
    }

    /// Writes an enum value (tag + payload) into the two slots of `dst`.
    fn emitEnumStore(self: *FnEmitter, dst: *const sema.Symbol, value: *ast.Expr) Error!void {
        const operand = try self.enumOperand(value);
        try self.emit("  store i32 {s}, ptr {s}, align 4\n", .{ operand.tag, try self.varName(dst.slot) });
        try self.emit("  store i32 {s}, ptr {s}, align 4\n", .{ operand.payload, try self.varName(dst.slot + 1) });
    }

    /// `switch` over an enum variable: one block per arm, `switch` on the tag
    /// and the payload copied into the binding slot at the start of the arm.
    fn emitSwitch(self: *FnEmitter, sw: *ast.Stmt.SwitchStmt) Error!void {
        if (sw.scrutinee.kind != .identifier) return error.MiscompiledAst;
        const subject = self.symbolAt(sw.scrutinee.resolved orelse return error.MiscompiledAst);
        if (subject.typ != .enumeration) return error.MiscompiledAst;
        const enum_id = sw.resolved_enum orelse return error.MiscompiledAst;

        const tag = try self.newTemp();
        try self.emit("  {s} = load i32, ptr {s}, align 4\n", .{ tag, try self.varName(subject.slot) });

        const end_label = try self.newLabel("switch_end");
        const arm_labels = try self.arena.alloc([]const u8, sw.arms.len);
        for (sw.arms, 0..) |_, i| arm_labels[i] = try self.newLabel("switch_case");
        const default_label = if (sw.else_body != null) try self.newLabel("switch_else") else end_label;

        var list: std.ArrayList(u8) = .empty;
        for (sw.arms, 0..) |arm, i| {
            const case_tag = try self.caseTag(enum_id, arm.resolved_case orelse return error.MiscompiledAst);
            if (i > 0) try list.appendSlice(self.arena, " ");
            try list.print(self.arena, "i32 {s}, label %{s}", .{ case_tag, arm_labels[i] });
        }
        try self.emit("  switch i32 {s}, label %{s} [ {s} ]\n", .{ tag, default_label, list.items });
        self.block().terminated = true;

        for (sw.arms, 0..) |*arm, i| {
            try self.startBlock(arm_labels[i]);
            if (arm.binding_symbol) |symbol_index| {
                const binding = self.symbolAt(symbol_index);
                const payload = try self.newTemp();
                try self.emit("  {s} = load i32, ptr {s}, align 4\n", .{ payload, try self.varName(subject.slot + 1) });
                try self.emit("  store i32 {s}, ptr {s}, align 4\n", .{ payload, try self.varName(binding.slot) });
            }
            try self.emitStatements(arm.body);
            try self.br(end_label);
        }

        if (sw.else_body) |body| {
            try self.startBlock(default_label);
            try self.emitStatements(body);
            try self.br(end_label);
        }

        try self.startBlock(end_label);
    }

    fn emitExpr(self: *FnEmitter, expr: *ast.Expr) Error!Operand {
        switch (expr.kind) {
            .int_literal => |lit| {
                const text = try std.fmt.allocPrint(self.arena, "{d}", .{lit.value});
                return .{ .text = text, .typ = .i32 };
            },

            .bool_literal => |value| {
                return .{ .text = if (value) "true" else "false", .typ = .bool };
            },

            .identifier => {
                const symbol = self.symbolAt(expr.resolved orelse return error.MiscompiledAst);
                // `str` is two slots: it is only copied/printed by dedicated
                // routines, and semantics refuses to use it as a scalar.
                if (symbol.typ == .str) return error.MiscompiledAst;
                const ty = try llvmType(symbol.typ);
                const align_value = try typeAlign(symbol.typ);
                const name = try self.varName(symbol.slot);
                const result = try self.newTemp();
                try self.emit("  {s} = load {s}, ptr {s}, align {d}\n", .{ result, ty, name, align_value });
                return .{ .text = result, .typ = symbol.typ };
            },

            .unary => |unary| return self.emitUnary(expr, unary),

            .binary => |binary| return self.emitBinary(binary),

            .call => |call| return self.emitCall(call),

            .field_access => |access| {
                // An enum case (`Color.Red`) is tag + payload slots, not an operand.
                if (access.resolved_enum != null) return error.UnsupportedNode;
                const base = self.symbolAt(access.base.resolved orelse return error.MiscompiledAst);
                if (base.typ != .aggregate) return error.MiscompiledAst;
                const field_index = access.field_index orelse return error.MiscompiledAst;
                if (base.struct_id >= self.checked.structs.len) return error.MiscompiledAst;
                const field_type = self.checked.structs[base.struct_id].fields[field_index].typ;

                const ty = try llvmType(field_type);
                const align_value = try typeAlign(field_type);
                const name = try self.varName(base.slot + 1 + field_index);
                const result = try self.newTemp();
                try self.emit("  {s} = load {s}, ptr {s}, align {d}\n", .{ result, ty, name, align_value });
                return .{ .text = result, .typ = field_type };
            },

            // A whole struct is not an operand: `let`/assignment handle it
            // field by field in `emitStructStore`.
            .struct_literal => return error.UnsupportedNode,
            // `value.method(args)`: the receiver is argument 1. Values that do
            // not fit in an operand (struct, `str`, enum) go through
            // `enumOperand`/`strOperand`/`structFieldValues`.
            .method_call => {
                const ref = (try callRefOf(expr)) orelse return error.UnsupportedNode;
                return self.emitCallWith(ref.index, ref.site);
            },
            // `str` is two slots (pointer + length), handled by
            // `emitStrStore` and `emitPrint`.
            .str_literal => return error.UnsupportedNode,
        }
    }

    /// Writes a `str` value (pointer and length) into the two slots of `dst`:
    /// a direct literal or a copy of another `str` variable.
    /// Textual operands of a `str` value: pointer and length. Covers literal,
    /// variable and call returning `str` (through `extractvalue`).
    const StrOperand = struct { ptr: []const u8, len: []const u8 };

    fn strOperand(self: *FnEmitter, expr: *ast.Expr) Error!StrOperand {
        switch (expr.kind) {
            .str_literal => |text| {
                const index = try self.state.strs.intern(text);
                return .{
                    .ptr = try std.fmt.allocPrint(self.arena, "@.str{d}", .{index}),
                    .len = try std.fmt.allocPrint(self.arena, "{d}", .{text.len}),
                };
            },
            .identifier => {
                const src = self.symbolAt(expr.resolved orelse return error.MiscompiledAst);
                if (src.typ != .str) return error.MiscompiledAst;
                const ptr_temp = try self.newTemp();
                try self.emit("  {s} = load ptr, ptr {s}, align 8\n", .{ ptr_temp, try self.varName(src.slot) });
                const len_temp = try self.newTemp();
                try self.emit("  {s} = load i64, ptr {s}, align 8\n", .{ len_temp, try self.varName(src.slot + 1) });
                return .{ .ptr = ptr_temp, .len = len_temp };
            },
            .call, .method_call => {
                const ref = (try callRefOf(expr)) orelse return error.MiscompiledAst;
                const pair = try self.emitStrCall(ref.index, ref.site);
                const ptr_temp = try self.newTemp();
                try self.emit("  {s} = extractvalue {{ ptr, i64 }} {s}, 0\n", .{ ptr_temp, pair });
                const len_temp = try self.newTemp();
                try self.emit("  {s} = extractvalue {{ ptr, i64 }} {s}, 1\n", .{ len_temp, pair });
                return .{ .ptr = ptr_temp, .len = len_temp };
            },
            else => return error.MiscompiledAst,
        }
    }

    fn emitStrStore(self: *FnEmitter, dst: *const sema.Symbol, value: *ast.Expr) Error!void {
        const src = try self.strOperand(value);
        try self.emit("  store ptr {s}, ptr {s}, align 8\n", .{ src.ptr, try self.varName(dst.slot) });
        try self.emit("  store i64 {s}, ptr {s}, align 8\n", .{ src.len, try self.varName(dst.slot + 1) });
    }

    /// `print(s)`: two libc `write` calls — the text and the line
    /// break. The `write` result is discarded (the language exposes no I/O
    /// primitives yet).
    fn emitPrint(self: *FnEmitter, call: ast.Expr.Call) Error!Operand {
        if (call.args.len != 1) return error.MiscompiledAst;
        const arg = call.args[0];

        const text = try self.strOperand(arg);
        try self.emit("  call i64 @write(i32 1, ptr {s}, i64 {s})\n", .{ text.ptr, text.len });
        try self.emit("  call i64 @write(i32 1, ptr @.nl, i64 1)\n", .{});
        self.state.used_print = true;
        return .{ .text = "", .typ = .void };
    }

    /// Copies a struct into the slots of `dst`: literal, another variable or
    /// call returning a struct (field by field, through `structFieldValues`).
    fn emitStructStore(self: *FnEmitter, dst: *const sema.Symbol, value: *ast.Expr) Error!void {
        const fields = try self.structFields(dst.struct_id);
        const values = try self.structFieldValues(value, dst.struct_id);
        for (fields, 0..) |field, i| {
            const ty = try llvmType(field.typ);
            const align_value = try typeAlign(field.typ);
            const name = try self.varName(dst.slot + 1 + @as(u32, @intCast(i)));
            try self.emit("  store {s} {s}, ptr {s}, align {d}\n", .{ ty, values[i], name, align_value });
        }
    }

    fn emitUnary(self: *FnEmitter, expr: *ast.Expr, unary: ast.Expr.Unary) Error!Operand {
        const operand = try self.emitExpr(unary.operand);
        if (operand.typ == .void) return error.UnsupportedNode;
        const result = try self.newTemp();
        switch (unary.op) {
            .neg => try self.emit("  {s} = sub i32 0, {s}\n", .{ result, operand.text }),
            .not => try self.emit("  {s} = xor i1 {s}, true\n", .{ result, operand.text }),
        }
        _ = expr;
        return .{
            .text = result,
            .typ = if (unary.op == .neg) .i32 else .bool,
        };
    }

    fn emitBinary(self: *FnEmitter, binary: ast.Expr.Binary) Error!Operand {
        if (binary.op.isLogical()) return self.emitLogical(binary);

        const lhs = try self.emitExpr(binary.lhs);
        const rhs = try self.emitExpr(binary.rhs);
        if (lhs.typ == .void or rhs.typ == .void) return error.UnsupportedNode;
        if (lhs.typ != rhs.typ) return error.UnsupportedNode;

        const ty = try llvmType(lhs.typ);
        const result = try self.newTemp();

        switch (binary.op) {
            .add => try self.emit("  {s} = add {s} {s}, {s}\n", .{ result, ty, lhs.text, rhs.text }),
            .sub => try self.emit("  {s} = sub {s} {s}, {s}\n", .{ result, ty, lhs.text, rhs.text }),
            .mul => try self.emit("  {s} = mul {s} {s}, {s}\n", .{ result, ty, lhs.text, rhs.text }),
            .div => try self.emit("  {s} = sdiv {s} {s}, {s}\n", .{ result, ty, lhs.text, rhs.text }),
            .mod => try self.emit("  {s} = srem {s} {s}, {s}\n", .{ result, ty, lhs.text, rhs.text }),
            .lt => try self.emit("  {s} = icmp slt {s} {s}, {s}\n", .{ result, ty, lhs.text, rhs.text }),
            .le => try self.emit("  {s} = icmp sle {s} {s}, {s}\n", .{ result, ty, lhs.text, rhs.text }),
            .gt => try self.emit("  {s} = icmp sgt {s} {s}, {s}\n", .{ result, ty, lhs.text, rhs.text }),
            .ge => try self.emit("  {s} = icmp sge {s} {s}, {s}\n", .{ result, ty, lhs.text, rhs.text }),
            .eq => try self.emit("  {s} = icmp eq {s} {s}, {s}\n", .{ result, ty, lhs.text, rhs.text }),
            .ne => try self.emit("  {s} = icmp ne {s} {s}, {s}\n", .{ result, ty, lhs.text, rhs.text }),
            .and_op, .or_op => unreachable,
        }

        return .{
            .text = result,
            .typ = if (binary.op.isArithmetic()) .i32 else .bool,
        };
    }

    /// `&&` and `||` with short-circuit, using blocks and `phi`.
    fn emitLogical(self: *FnEmitter, binary: ast.Expr.Binary) Error!Operand {
        const lhs = try self.emitExpr(binary.lhs);
        const is_and = binary.op == .and_op;

        const rhs_label = try self.newLabel(if (is_and) "and_rhs" else "or_rhs");
        const end_label = try self.newLabel(if (is_and) "and_end" else "or_end");
        const lhs_label = self.block().label;

        if (is_and) {
            try self.condBr(lhs.text, rhs_label, end_label);
        } else {
            try self.condBr(lhs.text, end_label, rhs_label);
        }

        try self.startBlock(rhs_label);
        const rhs = try self.emitExpr(binary.rhs);
        const rhs_source = self.block().label;
        try self.br(end_label);

        try self.startBlock(end_label);
        const result = try self.newTemp();
        const short_value = if (is_and) "false" else "true";
        try self.emit("  {s} = phi i1 [ {s}, %{s} ], [ {s}, %{s} ]\n", .{
            result, short_value, lhs_label, rhs.text, rhs_source,
        });
        return .{ .text = result, .typ = .bool };
    }

    /// `print_i32(n)`: calls the internal decimal formatting routine.
    fn emitPrintI32(self: *FnEmitter, call: ast.Expr.Call) Error!Operand {
        if (call.args.len != 1) return error.MiscompiledAst;
        const value = try self.emitExpr(call.args[0]);
        if (value.typ != .i32) return error.UnsupportedNode;
        try self.emit("  call void @kyn_print_i32(i32 {s})\n", .{value.text});
        self.state.used_print_i32 = true;
        return .{ .text = "", .typ = .void };
    }

    /// Argument list in IR form. `str` contributes two
    /// (`ptr` + `i64`), in the order the signature declares them.
    /// Arguments in callee order: the method receiver first, then the written
    /// arguments.
    fn emitArgs(
        self: *FnEmitter,
        site: codegen.Arguments,
        params: []const sema.Type,
        param_struct_ids: []const u32,
    ) Error![]const u8 {
        var args: std.ArrayList(u8) = .empty;
        for (0..site.count()) |i| {
            const arg = site.at(i);
            const ptype = if (i < params.len) params[i] else return error.MiscompiledAst;
            const struct_id = if (i < param_struct_ids.len) param_struct_ids[i] else 0;
            if (ptype == .aggregate) {
                // A struct becomes one argument per field, in declaration order.
                const fields = try self.structFields(struct_id);
                const values = try self.structFieldValues(arg, struct_id);
                for (fields, 0..) |field, field_index| {
                    if (args.items.len != 0) try args.appendSlice(self.arena, ", ");
                    try args.print(self.arena, "{s} {s}", .{ try llvmType(field.typ), values[field_index] });
                }
                continue;
            }
            if (args.items.len != 0) try args.appendSlice(self.arena, ", ");
            if (ptype == .str) {
                const text = try self.strOperand(arg);
                try args.print(self.arena, "ptr {s}, i64 {s}", .{ text.ptr, text.len });
            } else if (ptype == .enumeration) {
                const value = try self.enumOperand(arg);
                try args.print(self.arena, "i32 {s}, i32 {s}", .{ value.tag, value.payload });
            } else {
                const value = try self.emitExpr(arg);
                if (value.typ == .void) return error.UnsupportedNode;
                try args.print(self.arena, "{s} {s}", .{ try llvmType(value.typ), value.text });
            }
        }
        return args.items;
    }

    /// Call whose return is `str`: returns the temporary holding the `{ptr, i64}` pair.
    fn emitStrCall(self: *FnEmitter, fn_index: u32, site: codegen.Arguments) Error![]const u8 {
        const callee = self.checked.functions[fn_index];
        if (callee.return_type != .str) return error.MiscompiledAst;
        const args = try self.emitArgs(site, callee.params, callee.param_struct_ids);
        const result = try self.newTemp();
        try self.emit("  {s} = call {{ ptr, i64 }} @{s}({s})\n", .{ result, callee.symbol_name, args });
        return result;
    }

    /// Call whose return is an enum: returns the temporary holding
    /// `{ i32, i32 }`.
    fn emitEnumCall(self: *FnEmitter, fn_index: u32, site: codegen.Arguments) Error![]const u8 {
        const callee = self.checked.functions[fn_index];
        if (callee.return_type != .enumeration) return error.MiscompiledAst;
        const args = try self.emitArgs(site, callee.params, callee.param_struct_ids);
        const result = try self.newTemp();
        try self.emit("  {s} = call {{ i32, i32 }} @{s}({s})\n", .{ result, callee.symbol_name, args });
        return result;
    }

    /// Call expression: builtin or free function.
    fn emitCall(self: *FnEmitter, call: ast.Expr.Call) Error!Operand {
        if (call.builtin) |builtin| switch (builtin) {
            .print => return self.emitPrint(call),
            .print_i32 => return self.emitPrintI32(call),
        };
        return self.emitCallWith(call.callee_fn orelse return error.MiscompiledAst, .{ .list = call.args });
    }

    /// Call by resolved index: `site` carries the receiver of a method first.
    fn emitCallWith(self: *FnEmitter, fn_index: u32, site: codegen.Arguments) Error!Operand {
        const callee = self.checked.functions[fn_index];
        // `str`, struct and enum do not fit in an `Operand`: consumers use
        // `strOperand`, `enumOperand`, `emitEnumCall` and `emitStructCall`.
        if (callee.return_type == .str) return error.UnsupportedNode;
        if (callee.return_type == .aggregate) return error.UnsupportedNode;
        if (callee.return_type == .enumeration) return error.UnsupportedNode;

        const args = try self.emitArgs(site, callee.params, callee.param_struct_ids);

        const ret_type = try llvmType(callee.return_type);
        if (callee.return_type == .void) {
            try self.emit("  call void @{s}({s})\n", .{ callee.symbol_name, args });
            return .{ .text = "", .typ = .void };
        }

        const result = try self.newTemp();
        try self.emit("  {s} = call {s} @{s}({s})\n", .{ result, ret_type, callee.symbol_name, args });
        return .{ .text = result, .typ = callee.return_type };
    }
};

/// Body of `@kyn_print_i32`, emitted when `print_i32` is used.
///
/// 12-byte buffer written back to front: at most 10 digits plus the
/// sign. `sub i32 0, %arg0` is modular arithmetic (no `nsw`), so INT_MIN
/// becomes 0x80000000 and `udiv` produces 2147483648 — the text comes out as
/// `-2147483648`, which is correct.
const kyn_print_i32_ir =
    \\define internal void @kyn_print_i32(i32 %arg0) {
    \\entry:
    \\  %buf = alloca [12 x i8], align 1
    \\  %isneg = icmp slt i32 %arg0, 0
    \\  %negated = sub i32 0, %arg0
    \\  %mag = select i1 %isneg, i32 %negated, i32 %arg0
    \\  br label %loop
    \\loop:
    \\  %n = phi i32 [ %mag, %entry ], [ %q, %loop ]
    \\  %pos = phi i32 [ 12, %entry ], [ %posnext, %loop ]
    \\  %digit = urem i32 %n, 10
    \\  %ascii = add i32 %digit, 48
    \\  %byte = trunc i32 %ascii to i8
    \\  %posnext = sub i32 %pos, 1
    \\  %digitptr = getelementptr inbounds [12 x i8], ptr %buf, i64 0, i32 %posnext
    \\  store i8 %byte, ptr %digitptr, align 1
    \\  %q = udiv i32 %n, 10
    \\  %done = icmp eq i32 %q, 0
    \\  br i1 %done, label %sign, label %loop
    \\sign:
    \\  %negpos = sub i32 %posnext, 1
    \\  %negptr = getelementptr inbounds [12 x i8], ptr %buf, i64 0, i32 %negpos
    \\  br i1 %isneg, label %sign_store, label %write
    \\sign_store:
    \\  store i8 45, ptr %negptr, align 1
    \\  br label %write
    \\write:
    \\  %start = phi i32 [ %posnext, %sign ], [ %negpos, %sign_store ]
    \\  %len = sub i32 12, %start
    \\  %len64 = zext i32 %len to i64
    \\  %start64 = zext i32 %start to i64
    \\  %text = getelementptr inbounds [12 x i8], ptr %buf, i64 0, i64 %start64
    \\  call i64 @write(i32 1, ptr %text, i64 %len64)
    \\  call i64 @write(i32 1, ptr @.nl, i64 1)
    \\  ret void
    \\}
    \\
;

fn appendIndented(out: *std.ArrayList(u8), arena: std.mem.Allocator, text: []const u8) !void {
    var it = std.mem.splitScalar(u8, text, '\n');
    while (it.next()) |line| {
        if (line.len == 0) continue;
        try out.print(arena, "  {s}\n", .{line});
    }
}

