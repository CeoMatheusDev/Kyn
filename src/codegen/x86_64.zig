/// Initial value of a field inside a struct literal, by name.
fn findFieldInit(inits: []ast.Expr.FieldInit, name: []const u8) ?*ast.Expr {
    for (inits) |init| {
        if (std.mem.eql(u8, init.name, name)) return init.value;
    }
    return null;
}

