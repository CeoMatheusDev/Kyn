//! Native x86-64 backend (Linux, System V AMD64), no libc dependency.
//!
//! Strategy:
//! - every variable (parameter or local) gets an 8-byte slot in the frame;
//!   `i32`/`bool` use 4 bytes of the slot and are loaded as 32 bits;
//! - a struct variable takes one base slot (reserved) followed by one slot
//!   per field, in declaration order (`slot + 1 + index`); structs never
//!   escape the function (no by-value parameters/returns), so it fits in
//!   local variables;
//! - expressions are evaluated in `%eax` with a temporary stack;
//! - `str` is a slice (pointer + length) kept in two slots; in
//!   calls it occupies **two consecutive registers** (`%rdi/%rsi`,
//!   `%rdx/%rcx`, `%r8/%r9` — at most three `str` per call) and the return
//!   comes back in `%rax` (pointer) and `%rdx` (length);
//! - `_start` calls `kyn_main` and exits through the `exit` syscall (60) with
//!   the value returned by `main` (`0` when `main` is `void`).
//!
//! This backend is the validatable path: `as` + `ld` produce a binary that can
//! be run and checked through its exit code (see `tools/e2e.sh`).
//!
//! Known limits: up to 6 parameters (SysV registers), no external
//! calls, `bool` is materialized as 32 bits, no optimization.

const std = @import("std");
const ast = @import("../ast/ast.zig");
const sema = @import("../sema/sema.zig");
const codegen = @import("codegen.zig");

pub const Error = codegen.Error;

const arg_registers = [_][]const u8{ "%edi", "%esi", "%edx", "%ecx", "%r8d", "%r9d" };
/// 64-bit names of the same registers: used for `str` (pointer and
/// length are 8-byte values).
const arg_registers_64 = [_][]const u8{ "%rdi", "%rsi", "%rdx", "%rcx", "%r8", "%r9" };

/// Return registers of a struct: one per field, in declaration order.
/// They do not clash with the argument ones because the caller already used those.
const struct_return_registers = [_][]const u8{ "%eax", "%edx", "%ecx", "%r8d", "%r9d", "%r10d" };

/// The same registers in 64 bits, used when stacking a struct returned
/// by a call to pass it as an argument of another call.
const struct_return_registers_64 = [_][]const u8{ "%rax", "%rdx", "%rcx", "%r8", "%r9", "%r10" };

pub fn emit(
    arena: std.mem.Allocator,
    program: *const ast.Program,
    checked: *const sema.Checked,
) Error![]const u8 {
    var out: std.ArrayList(u8) = .empty;
    var state = codegen.ProgramState{ .strs = codegen.StrPool.init(arena) };

    // Process entry point: calls `kyn_main` and exits with a syscall.
    const main_index = checked.findFunction("main") orelse return error.UnsupportedNode;
    const main_info = checked.functions[main_index];

    try out.print(arena, "# assembly x86-64 (System V, Linux) generated by kync\n", .{});
    try out.print(arena, ".text\n", .{});
    try out.print(arena, ".globl _start\n", .{});
    try out.print(arena, "_start:\n", .{});
    try out.print(arena, "    call kyn_{s}\n", .{main_info.symbol_name});
    if (main_info.return_type == .void) {
        try out.print(arena, "    xorl %edi, %edi\n", .{});
    } else {
        try out.print(arena, "    movl %eax, %edi\n", .{});
    }
    try out.print(arena, "    movl $60, %eax\n", .{});
    try out.print(arena, "    syscall\n\n", .{});

    for (program.functions, 0..) |func, i| {
        var emitter = FnEmitter.init(arena, func, checked, checked.functions[i], &state);
        try emitter.emitFunction(&out);
        try out.append(arena, '\n');
    }

    // Decimal formatting routine, emitted once per program when
    // `print_i32` appears. It lives in `.text` (code), before the data: `divl` is
    // unsigned, so after `negl` INT_MIN becomes 0x80000000 and the loop produces
    // 2147483648 digits with a leading '-' — the correct result for
    // -2147483648. No libc and no global state.
    if (state.used_print_i32) {
        try out.print(arena, ".text\n", .{});
        try out.appendSlice(arena,
            \\.type kyn_print_i32, @function
            \\kyn_print_i32:
            \\    pushq %rbp
            \\    movq %rsp, %rbp
            \\    subq $32, %rsp
            \\    movl %edi, %eax
            \\    xorl %r8d, %r8d
            \\    testl %eax, %eax
            \\    jns .Lpi_abs
            \\    movl $1, %r8d
            \\    negl %eax
            \\.Lpi_abs:
            \\    leaq -12(%rbp), %rsi
            \\    movl $0, %ecx
            \\    movl $10, %r9d
            \\.Lpi_loop:
            \\    xorl %edx, %edx
            \\    divl %r9d
            \\    addl $48, %edx
            \\    decq %rsi
            \\    movb %dl, (%rsi)
            \\    incl %ecx
            \\    testl %eax, %eax
            \\    jne .Lpi_loop
            \\    testl %r8d, %r8d
            \\    je .Lpi_write
            \\    decq %rsi
            \\    movb $45, (%rsi)
            \\    incl %ecx
            \\.Lpi_write:
            \\    movl $1, %eax
            \\    movl $1, %edi
            \\    movq %rcx, %rdx
            \\    syscall
            \\    leaq .Lnl(%rip), %rsi
            \\    movq $1, %rdx
            \\    movl $1, %eax
            \\    movl $1, %edi
            \\    syscall
            \\    movq %rbp, %rsp
            \\    popq %rbp
            \\    ret
            \\.size kyn_print_i32, .-kyn_print_i32
            \\
        );
    }

    // Footer: string constants (deduplicated) and the line break used by
    // `print`. They are emitted only when the program uses that feature.
    if (state.strs.texts.items.len > 0 or state.used_print or state.used_print_i32) {
        try out.print(arena, ".section .rodata\n", .{});
        for (state.strs.texts.items, 0..) |text, index| {
            try out.print(arena, ".Lstr{d}:\n", .{index});
            if (text.len == 0) {
                // `as` does not accept `.byte` without operands; one padding byte
                // keeps the label valid for zero length (nothing is written).
                try out.print(arena, "    .zero 1\n", .{});
            } else {
                try out.print(arena, "    .byte ", .{});
                for (text, 0..) |byte, byte_index| {
                    if (byte_index != 0) try out.print(arena, ", ", .{});
                    try out.print(arena, "{d}", .{byte});
                }
                try out.print(arena, "\n", .{});
            }
        }
        if (state.used_print or state.used_print_i32) {
            try out.print(arena, ".Lnl:\n    .byte 10\n", .{});
        }
    }

    try out.print(arena, ".section .note.GNU-stack,\"\",@progbits\n", .{});
    return out.toOwnedSlice(arena);
}

const FnEmitter = struct {
    arena: std.mem.Allocator,
    func: *const ast.Function,
    checked: *const sema.Checked,
    info: sema.FunctionInfo,
    out: *std.ArrayList(u8) = undefined,
    /// Shared program state (string pool and `print` usage).
    state: *codegen.ProgramState,
    label_count: u32 = 0,
    /// Has the current block already ended (return)? Avoids unreachable code.
    terminated: bool = false,

    fn init(
        arena: std.mem.Allocator,
        func: *const ast.Function,
        checked: *const sema.Checked,
        info: sema.FunctionInfo,
        state: *codegen.ProgramState,
    ) FnEmitter {
        return .{ .arena = arena, .func = func, .checked = checked, .info = info, .state = state };
    }

    fn print(self: *FnEmitter, comptime fmt: []const u8, args: anytype) !void {
        try self.out.print(self.arena, fmt, args);
    }

    fn label(self: *FnEmitter, prefix: []const u8) ![]const u8 {
        const name = try std.fmt.allocPrint(self.arena, ".L{s}_{s}_{d}", .{
            self.func.name, prefix, self.label_count,
        });
        self.label_count += 1;
        return name;
    }

    fn slotOffset(slot: u32) u32 {
        return 8 * (slot + 1);
    }

    fn symbolAt(self: *FnEmitter, index: u32) *const sema.Symbol {
        return &self.checked.symbols[index];
    }

    /// Register words the type consumes (struct: one per field).
    fn registerWordsOf(self: *FnEmitter, typ: sema.Type, struct_id: u32) usize {
        return sema.registerWordsOf(self.checked.structs, typ, struct_id);
    }

    fn structFields(self: *FnEmitter, struct_id: u32) Error![]const sema.FieldInfo {
        if (struct_id >= self.checked.structs.len) return error.MiscompiledAst;
        return self.checked.structs[struct_id].fields;
    }

    fn emitFunction(self: *FnEmitter, out: *std.ArrayList(u8)) !void {
        self.out = out;

        // `str` consumes two registers and each struct field one;
        // semantics already limits the total.
        var register_words: usize = 0;
        for (self.info.params, 0..) |ptype, i| {
            const struct_id = if (i < self.info.param_struct_ids.len) self.info.param_struct_ids[i] else 0;
            register_words += self.registerWordsOf(ptype, struct_id);
        }
        if (register_words > arg_registers.len) return error.UnsupportedNode;

        const frame_bytes: u32 = std.mem.alignForward(u32, self.info.slot_count * 8, 16);

        try self.print(".type kyn_{s}, @function\n", .{self.info.symbol_name});
        try self.print("kyn_{s}:\n", .{self.info.symbol_name});
        try self.print("    pushq %rbp\n", .{});
        try self.print("    movq %rsp, %rbp\n", .{});
        if (frame_bytes > 0) {
            try self.print("    subq ${d}, %rsp\n", .{frame_bytes});
        }

        // Parameters: registers -> slots. `str` stores pointer and length.
        var reg: usize = 0;
        for (self.func.params, 0..) |_, i| {
            const sym = &self.checked.symbols[self.info.symbol_start + i];
            if (sym.typ == .aggregate) {
                if (sym.struct_id >= self.checked.structs.len) return error.MiscompiledAst;
                const fields = self.checked.structs[sym.struct_id].fields;
                for (fields, 0..) |_, field_index| {
                    try self.print("    movl {s}, -{d}(%rbp)\n", .{
                        arg_registers[reg],
                        slotOffset(sym.slot + 1 + @as(u32, @intCast(field_index))),
                    });
                    reg += 1;
                }
                continue;
            }
            if (sym.typ == .str) {
                try self.print("    movq {s}, -{d}(%rbp)\n", .{ arg_registers_64[reg], slotOffset(sym.slot) });
                try self.print("    movq {s}, -{d}(%rbp)\n", .{ arg_registers_64[reg + 1], slotOffset(sym.slot + 1) });
                reg += 2;
            } else if (sym.typ == .enumeration) {
                // Tag and payload, in that order (the same pair as the return).
                try self.print("    movl {s}, -{d}(%rbp)\n", .{ arg_registers[reg], slotOffset(sym.slot) });
                try self.print("    movl {s}, -{d}(%rbp)\n", .{ arg_registers[reg + 1], slotOffset(sym.slot + 1) });
                reg += 2;
            } else {
                try self.print("    movl {s}, -{d}(%rbp)\n", .{ arg_registers[reg], slotOffset(sym.slot) });
                reg += 1;
            }
        }

        try self.emitStatements(self.func.body);

        if (!self.terminated) {
            if (self.info.return_type != .void) {
                try self.print("    xorl %eax, %eax\n", .{});
            }
            try self.print("    movq %rbp, %rsp\n", .{});
            try self.print("    popq %rbp\n", .{});
            try self.print("    ret\n", .{});
            self.terminated = true;
        }

        try self.print(".size kyn_{s}, .-kyn_{s}\n", .{ self.info.symbol_name, self.info.symbol_name });
    }

    fn emitStatements(self: *FnEmitter, stmts: []*ast.Stmt) Error!void {
        for (stmts) |stmt| {
            if (self.terminated) return;
            try self.emitStatement(stmt);
        }
    }

    fn emitStatement(self: *FnEmitter, stmt: *ast.Stmt) Error!void {
        switch (stmt.kind) {
            .let_decl => |decl| {
                const symbol = self.symbolAt(stmt.decl_symbol orelse return error.MiscompiledAst);
                if (symbol.typ == .aggregate) {
                    try self.emitStructStore(symbol, decl.init);
                } else if (symbol.typ == .str) {
                    try self.emitStrStore(symbol, decl.init);
                } else if (symbol.typ == .enumeration) {
                    try self.emitEnumStore(symbol, decl.init);
                } else {
                    try self.emitExpr(decl.init);
                    try self.print("    movl %eax, -{d}(%rbp)\n", .{slotOffset(symbol.slot)});
                }
            },

            .assign => |assign| {
                const symbol = self.symbolAt(assign.resolved orelse return error.MiscompiledAst);
                if (symbol.typ == .aggregate) {
                    try self.emitStructStore(symbol, assign.value);
                } else if (symbol.typ == .str) {
                    try self.emitStrStore(symbol, assign.value);
                } else if (symbol.typ == .enumeration) {
                    try self.emitEnumStore(symbol, assign.value);
                } else {
                    try self.emitExpr(assign.value);
                    try self.print("    movl %eax, -{d}(%rbp)\n", .{slotOffset(symbol.slot)});
                }
            },

            .field_assign => |field_assign| {
                const base = self.symbolAt(field_assign.base.resolved orelse return error.MiscompiledAst);
                if (base.typ != .aggregate) return error.MiscompiledAst;
                const field_index = field_assign.field_index orelse return error.MiscompiledAst;
                try self.emitExpr(field_assign.value);
                try self.print("    movl %eax, -{d}(%rbp)\n", .{
                    slotOffset(base.slot + 1 + field_index),
                });
            },

            .return_stmt => |maybe_expr| {
                if (maybe_expr) |expr| {
                    if (self.info.return_type == .str) {
                        // Slice returned in `%rax` (pointer) and `%rdx` (length).
                        try self.emitStrValue(expr);
                    } else if (self.info.return_type == .aggregate) {
                        // A struct returns with one register per field.
                        try self.emitStructReturn(expr);
                    } else if (self.info.return_type == .enumeration) {
                        // Enum: tag in `%eax`, payload in `%edx`.
                        try self.emitEnumValue(expr);
                    } else {
                        try self.emitExpr(expr);
                    }
                } else if (self.info.return_type != .void) {
                    return error.MiscompiledAst;
                }
                try self.print("    movq %rbp, %rsp\n", .{});
                try self.print("    popq %rbp\n", .{});
                try self.print("    ret\n", .{});
                self.terminated = true;
            },

            .expr_stmt => |expr| try self.emitExpr(expr),

            .if_stmt => |if_stmt| {
                const else_label = try self.label("else");
                const end_label = try self.label("endif");

                try self.emitExpr(if_stmt.cond);
                try self.print("    cmpl $0, %eax\n", .{});
                try self.print("    je {s}\n", .{else_label});

                try self.emitStatements(if_stmt.then_body);
                const then_terminated = self.terminated;
                if (!then_terminated) try self.print("    jmp {s}\n", .{end_label});

                try self.print("{s}:\n", .{else_label});
                self.terminated = false;
                if (if_stmt.else_body) |else_branch| {
                    switch (else_branch) {
                        .block => |stmts| try self.emitStatements(stmts),
                        .if_stmt => |nested| try self.emitStatement(nested),
                    }
                }
                const else_terminated = self.terminated;
                if (!else_terminated) try self.print("    jmp {s}\n", .{end_label});

                try self.print("{s}:\n", .{end_label});
                self.terminated = then_terminated and else_terminated;
            },

            .while_stmt => |while_stmt| {
                const cond_label = try self.label("while_cond");
                const end_label = try self.label("while_end");

                try self.print("{s}:\n", .{cond_label});
                self.terminated = false;
                try self.emitExpr(while_stmt.cond);
                try self.print("    cmpl $0, %eax\n", .{});
                try self.print("    je {s}\n", .{end_label});

                try self.emitStatements(while_stmt.body);
                self.terminated = false;
                try self.print("    jmp {s}\n", .{cond_label});
                try self.print("{s}:\n", .{end_label});
                self.terminated = false;
            },

            .switch_stmt => |*sw| try self.emitSwitch(sw),

            .block => |stmts| try self.emitStatements(stmts),
        }
    }

    /// Tag of an enum case, verified against the checked program.
    fn caseTag(self: *FnEmitter, enum_id: u32, case_index: u32) Error!i32 {
        if (enum_id >= self.checked.enums.len) return error.MiscompiledAst;
        const info = &self.checked.enums[enum_id];
        if (case_index >= info.cases.len) return error.MiscompiledAst;
        return info.cases[case_index].tag;
    }

    /// Leaves an enum value in `%eax` (tag) and `%edx` (payload) — the same
    /// convention as a function returning an enum, which lets calls be reused.
    fn emitEnumValue(self: *FnEmitter, value: *ast.Expr) Error!void {
        switch (value.kind) {
            .field_access => |access| {
                const tag = try self.caseTag(
                    access.resolved_enum orelse return error.MiscompiledAst,
                    access.resolved_case orelse return error.MiscompiledAst,
                );
                try self.print("    movl ${d}, %eax\n", .{tag});
                try self.print("    movl $0, %edx\n", .{});
            },
            .method_call => |call| {
                // A method returning an enum leaves the pair in `%eax`/`%edx`,
                // the same place a constructor writes it.
                if (call.resolved_fn) |index| {
                    if (self.checked.functions[index].return_type != .enumeration) return error.MiscompiledAst;
                    try self.emitCallWith(index, .{ .receiver = call.base, .list = call.args });
                    return;
                }
                const tag = try self.caseTag(
                    call.resolved_enum orelse return error.MiscompiledAst,
                    call.resolved_case orelse return error.MiscompiledAst,
                );
                if (call.args.len != 1) return error.MiscompiledAst;
                // The payload is evaluated first: it may use `%edx` itself
                // (`idivl`), so the tag is written afterwards.
                try self.emitExpr(call.args[0]);
                try self.print("    movl %eax, %edx\n", .{});
                try self.print("    movl ${d}, %eax\n", .{tag});
            },
            .identifier => {
                const src = self.symbolAt(value.resolved orelse return error.MiscompiledAst);
                if (src.typ != .enumeration) return error.MiscompiledAst;
                try self.print("    movl -{d}(%rbp), %eax\n", .{slotOffset(src.slot)});
                try self.print("    movl -{d}(%rbp), %edx\n", .{slotOffset(src.slot + 1)});
            },
            .call => {
                const ref = (try callRefOf(value)) orelse return error.MiscompiledAst;
                if (self.checked.functions[ref.index].return_type != .enumeration) return error.MiscompiledAst;
                try self.emitCallWith(ref.index, ref.site);
            },
            else => return error.MiscompiledAst,
        }
    }

    /// Writes an enum value (tag + payload) into the two slots of `dst`.
    fn emitEnumStore(self: *FnEmitter, dst: *const sema.Symbol, value: *ast.Expr) Error!void {
        try self.emitEnumValue(value);
        try self.print("    movl %eax, -{d}(%rbp)\n", .{slotOffset(dst.slot)});
        try self.print("    movl %edx, -{d}(%rbp)\n", .{slotOffset(dst.slot + 1)});
    }

    /// `switch` over an enum variable: compare the tag against each case and
    /// jump; the payload is copied into the binding slot at the arm start.
    fn emitSwitch(self: *FnEmitter, sw: *ast.Stmt.SwitchStmt) Error!void {
        if (sw.scrutinee.kind != .identifier) return error.MiscompiledAst;
        const subject = self.symbolAt(sw.scrutinee.resolved orelse return error.MiscompiledAst);
        if (subject.typ != .enumeration) return error.MiscompiledAst;
        const enum_id = sw.resolved_enum orelse return error.MiscompiledAst;

        const end_label = try self.label("switch_end");
        const arm_labels = try self.arena.alloc([]const u8, sw.arms.len);
        for (sw.arms, 0..) |_, i| arm_labels[i] = try self.label("switch_case");
        const else_label = if (sw.else_body != null) try self.label("switch_else") else end_label;

        try self.print("    movl -{d}(%rbp), %eax\n", .{slotOffset(subject.slot)});
        for (sw.arms, 0..) |arm, i| {
            const tag = try self.caseTag(enum_id, arm.resolved_case orelse return error.MiscompiledAst);
            try self.print("    cmpl ${d}, %eax\n", .{tag});
            try self.print("    je {s}\n", .{arm_labels[i]});
        }
        try self.print("    jmp {s}\n", .{else_label});

        for (sw.arms, 0..) |*arm, i| {
            try self.print("{s}:\n", .{arm_labels[i]});
            if (arm.binding_symbol) |symbol_index| {
                const binding = self.symbolAt(symbol_index);
                try self.print("    movl -{d}(%rbp), %eax\n", .{slotOffset(subject.slot + 1)});
                try self.print("    movl %eax, -{d}(%rbp)\n", .{slotOffset(binding.slot)});
            }
            try self.emitStatements(arm.body);
            if (!self.terminated) try self.print("    jmp {s}\n", .{end_label});
            self.terminated = false;
        }

        if (sw.else_body) |body| {
            try self.print("{s}:\n", .{else_label});
            try self.emitStatements(body);
            self.terminated = false;
        }

        try self.print("{s}:\n", .{end_label});
    }

    fn emitExpr(self: *FnEmitter, expr: *ast.Expr) Error!void {
        switch (expr.kind) {
            .int_literal => |lit| {
                if (lit.value > std.math.maxInt(i32) or lit.value < std.math.minInt(i32)) {
                    return error.UnsupportedNode;
                }
                try self.print("    movl ${d}, %eax\n", .{@as(i32, @intCast(lit.value))});
            },

            .bool_literal => |value| {
                try self.print("    movl ${d}, %eax\n", .{@as(u8, if (value) 1 else 0)});
            },

            .identifier => {
                const symbol = self.symbolAt(expr.resolved orelse return error.MiscompiledAst);
                // `str` does not fit in `%eax`: it is only copied/printed by dedicated
                // routines, and semantics refuses to use it as a scalar.
                if (symbol.typ == .str) return error.MiscompiledAst;
                try self.print("    movl -{d}(%rbp), %eax\n", .{slotOffset(symbol.slot)});
            },

            .unary => |unary| {
                try self.emitExpr(unary.operand);
                switch (unary.op) {
                    .neg => try self.print("    negl %eax\n", .{}),
                    .not => {
                        try self.print("    cmpl $0, %eax\n", .{});
                        try self.print("    sete %al\n", .{});
                        try self.print("    movzbl %al, %eax\n", .{});
                    },
                    .bitnot => try self.print("    notl %eax\n", .{}),
                }
            },

            .binary => |binary| {
                if (binary.op.isLogical()) {
                    try self.emitLogical(binary);
                } else {
                    try self.emitBinaryOp(binary);
                }
            },

            .call => |call| {
                // A struct value does not fit in `%eax`: consumers use
                // `emitStructStore`/`emitStructReturn`/`emitCall` directly.
                if (call.callee_fn) |index| {
                    if (self.checked.functions[index].return_type == .aggregate) {
                        return error.UnsupportedNode;
                    }
                }
                try self.emitCall(call);
            },

            // `value.method(args)`: the receiver is argument 1. Only scalars fit
            // in `%eax`; the other value types go through their own helpers.
            .method_call => {
                const ref = (try callRefOf(expr)) orelse return error.UnsupportedNode;
                if (!self.checked.functions[ref.index].return_type.isValue() and
                    self.checked.functions[ref.index].return_type != .void)
                {
                    return error.UnsupportedNode;
                }
                try self.emitCallWith(ref.index, ref.site);
            },

            .field_access => |access| {
                // An enum case (`Color.Red`) is tag + payload slots, not an operand.
                if (access.resolved_enum != null) return error.UnsupportedNode;
                const base = self.symbolAt(access.base.resolved orelse return error.MiscompiledAst);
                if (base.typ != .aggregate) return error.MiscompiledAst;
                const field_index = access.field_index orelse return error.MiscompiledAst;
                try self.print("    movl -{d}(%rbp), %eax\n", .{
                    slotOffset(base.slot + 1 + field_index),
                });
            },

            // A struct value does not fit in `%eax`: `let`/assignment handle the
            // literal field by field in `emitStructStore`.
            .struct_literal => return error.UnsupportedNode,
            // `str` is two slots (pointer + length), handled by
            // `emitStrStore` and `emitPrint`.
            .str_literal => return error.UnsupportedNode,

            // `expr as Type` — explicit integer width conversion.
            .cast => |cast_expr| {
                const src_type = try self.exprType(cast_expr.expr);
                if (src_type == .unknown) return error.MiscompiledAst;

                const dst_width = try self.intWidthOfTypeName(cast_expr.type_name);
                const src_width = src_type.bitWidth();
                if (dst_width == 0 or src_width == 0) return error.UnsupportedType;

                try self.emitExpr(cast_expr.expr);

                const src_reg = try self.regForWidth(src_width);
                const dst_reg = try self.regForWidth(dst_width);

                if (dst_width == src_width) {
                    // No-op: value already in the right-width register.
                    if (!std.mem.eql(u8, src_reg, dst_reg)) try self.print("    mov {s}, {s}", .{src_reg, dst_reg});
                    try self.out.appendSlice(self.arena, "\n");
                    return;
                }

                if (dst_width < src_width) {
                    // Truncation: no instruction needed; the low part of the
                    // source register already holds the truncated value.
                } else if (src_type.isSigned()) {
                    // Sign extension.
                    try self.print("    movsx {s}, {s}", .{src_reg, dst_reg});
                    try self.out.appendSlice(self.arena, "\n");
                } else {
                    // Zero extension.
                    try self.print("    movzx {s}, {s}", .{src_reg, dst_reg});
                    try self.out.appendSlice(self.arena, "\n");
                }
            },
        }
    }

    /// Determines the type of an expression without emitting code, walking only
    /// the constructs that can appear as the source of a `cast`.
    fn exprType(self: *FnEmitter, expr: *const ast.Expr) Error!sema.Type {
        return switch (expr.kind) {
            .int_literal => .i32,
            .bool_literal => .bool,
            .identifier => {
                const sym = self.symbolAt(expr.resolved orelse return error.MiscompiledAst);
                return sym.typ;
            },
            .binary => |binary| self.exprType(binary.lhs),
            .unary => |unary| {
                if (unary.op == .not) return .bool;
                return self.exprType(unary.operand);
            },
            .call => |call| {
                const index = call.callee_fn orelse return error.MiscompiledAst;
                return self.checked.functions[index].return_type;
            },
            .cast => |cast_expr| {
                const width = try self.intWidthOfTypeName(cast_expr.type_name);
                return try self.typeOfWidth(width);
            },
            .field_access => |access| {
                const base = self.symbolAt(access.base.resolved orelse return error.MiscompiledAst);
                if (base.typ != .aggregate) return error.MiscompiledAst;
                const field_index = access.field_index orelse return error.MiscompiledAst;
                return self.checked.structs[base.struct_id].fields[field_index].typ;
            },
            else => .unknown,
        };
    }

    /// Returns the register name for a given integer bit width.
    fn regForWidth(self: *FnEmitter, width: u32) Error![]const u8 {
        _ = self;
        return switch (width) {
            8 => "%al",
            16 => "%ax",
            32 => "%eax",
            64 => "%rax",
            else => error.UnsupportedType,
        };
    }

    /// Resolves a type name written in `expr as Type` to its bit width.
    fn intWidthOfTypeName(self: *FnEmitter, tn: ast.TypeName) Error!u32 {
        _ = self;
        const name = tn.name;
        if (std.mem.eql(u8, name, "i8") or std.mem.eql(u8, name, "u8")) return 8;
        if (std.mem.eql(u8, name, "i16") or std.mem.eql(u8, name, "u16")) return 16;
        if (std.mem.eql(u8, name, "i32") or std.mem.eql(u8, name, "u32")) return 32;
        if (std.mem.eql(u8, name, "i64") or std.mem.eql(u8, name, "u64") or std.mem.eql(u8, name, "usize")) return 64;
        return error.UnsupportedType;
    }

    /// Maps an integer bit width back to a sema.Type for result typing.
    fn typeOfWidth(self: *FnEmitter, width: u32) Error!sema.Type {
        _ = self;
        return switch (width) {
            8 => .i8,
            16 => .i16,
            32 => .i32,
            64 => .i64,
            else => error.UnsupportedType,
        };
    }

    /// Copies a struct value into the slots of `dst`: literal (each field
    /// evaluated and stored) or struct variable (field-by-field copy).
    fn emitStructStore(self: *FnEmitter, dst: *const sema.Symbol, value: *ast.Expr) Error!void {
        if (dst.struct_id >= self.checked.structs.len) return error.MiscompiledAst;
        const info = &self.checked.structs[dst.struct_id];

        switch (value.kind) {
            .struct_literal => |lit| {
                for (info.fields, 0..) |field, i| {
                    const init_value = findFieldInit(lit.fields, field.name) orelse return error.MiscompiledAst;
                    const index: u32 = @intCast(i);
                    try self.emitExpr(init_value);
                    try self.print("    movl %eax, -{d}(%rbp)\n", .{
                        slotOffset(dst.slot + 1 + index),
                    });
                }
            },
            .identifier => {
                const src = self.symbolAt(value.resolved orelse return error.MiscompiledAst);
                if (src.typ != .aggregate) return error.MiscompiledAst;
                for (info.fields, 0..) |_, i| {
                    const index: u32 = @intCast(i);
                    try self.print("    movl -{d}(%rbp), %eax\n", .{
                        slotOffset(src.slot + 1 + index),
                    });
                    try self.print("    movl %eax, -{d}(%rbp)\n", .{
                        slotOffset(dst.slot + 1 + index),
                    });
                }
            },
            .call, .method_call => {
                const ref = (try callRefOf(value)) orelse return error.MiscompiledAst;
                if (info.fields.len > struct_return_registers.len) return error.UnsupportedNode;
                try self.emitCallWith(ref.index, ref.site);
                for (info.fields, 0..) |_, i| {
                    const index: u32 = @intCast(i);
                    try self.print("    movl {s}, -{d}(%rbp)\n", .{
                        struct_return_registers[i],
                        slotOffset(dst.slot + 1 + index),
                    });
                }
            },
            else => return error.MiscompiledAst,
        }
    }

    /// Leaves a struct in `struct_return_registers`: one per field, in
    /// declaration order. Fields are evaluated on the stack so that one does not
    /// clobber another's result.
    fn emitStructReturn(self: *FnEmitter, value: *ast.Expr) Error!void {
        const fields = try self.structFields(self.info.return_struct_id);
        if (fields.len > struct_return_registers.len) return error.UnsupportedNode;

        switch (value.kind) {
            .identifier => {
                const src = self.symbolAt(value.resolved orelse return error.MiscompiledAst);
                if (src.typ != .aggregate) return error.MiscompiledAst;
                for (fields, 0..) |_, i| {
                    const index: u32 = @intCast(i);
                    try self.print("    movl -{d}(%rbp), {s}\n", .{
                        slotOffset(src.slot + 1 + index),
                        struct_return_registers[i],
                    });
                }
            },
            .call, .method_call => {
                const ref = (try callRefOf(value)) orelse return error.MiscompiledAst;
                try self.emitCallWith(ref.index, ref.site);
            },
            .struct_literal => |lit| {
                for (fields, 0..) |field, i| {
                    const init_value = findFieldInit(lit.fields, field.name) orelse return error.MiscompiledAst;
                    try self.emitExpr(init_value);
                    try self.print("    pushq %rax\n", .{});
                    _ = i;
                }
                var i: usize = fields.len;
                while (i > 0) {
                    i -= 1;
                    try self.print("    popq %rax\n", .{});
                    try self.print("    movl %eax, {s}\n", .{struct_return_registers[i]});
                }
            },
            else => return error.MiscompiledAst,
        }
    }

    /// Call site of an expression: a free call (`list` = written arguments) or a
    /// method call (`receiver` = `base`). `null` for anything else — including an
    /// enum constructor, which is not a call.
    const CallRef = struct { index: u32, site: codegen.Arguments };

    fn callRefOf(expr: *ast.Expr) Error!?CallRef {
        return switch (expr.kind) {
            .call => |call| .{
                .index = call.callee_fn orelse return error.MiscompiledAst,
                .site = .{ .list = call.args },
            },
            .method_call => |call| if (call.resolved_fn) |index| .{
                .index = index,
                .site = .{ .receiver = call.base, .list = call.args },
            } else null,
            else => null,
        };
    }

    /// Pushes a struct field by field (for by-value argument passing in calls).
    fn emitStructArgsPush(self: *FnEmitter, struct_id: u32, value: *ast.Expr) Error!void {
        const fields = try self.structFields(struct_id);

        switch (value.kind) {
            .identifier => {
                const src = self.symbolAt(value.resolved orelse return error.MiscompiledAst);
                if (src.typ != .aggregate) return error.MiscompiledAst;
                for (fields, 0..) |_, i| {
                    const index: u32 = @intCast(i);
                    try self.print("    movl -{d}(%rbp), %eax\n", .{
                        slotOffset(src.slot + 1 + index),
                    });
                    try self.print("    pushq %rax\n", .{});
                }
            },
            .struct_literal => |lit| {
                for (fields) |field| {
                    const init_value = findFieldInit(lit.fields, field.name) orelse return error.MiscompiledAst;
                    try self.emitExpr(init_value);
                    try self.print("    pushq %rax\n", .{});
                }
            },
            .call, .method_call => {
                const ref = (try callRefOf(value)) orelse return error.MiscompiledAst;
                if (fields.len > struct_return_registers.len) return error.UnsupportedNode;
                try self.emitCallWith(ref.index, ref.site);
                for (fields, 0..) |_, i| {
                    try self.print("    pushq {s}\n", .{struct_return_registers_64[i]});
                }
            },
            else => return error.MiscompiledAst,
        }
    }

    /// Writes a `str` value (pointer and length) into the two slots of `dst`:
    /// a direct literal or a copy of another `str` variable.
    /// Leaves a `str` value in `%rax` (pointer) and `%rdx` (length) — the same
    /// convention as function returns, which lets calls be reused.
    fn emitStrValue(self: *FnEmitter, value: *ast.Expr) Error!void {
        switch (value.kind) {
            .str_literal => |text| {
                const index = try self.state.strs.intern(text);
                try self.print("    leaq .Lstr{d}(%rip), %rax\n", .{index});
                try self.print("    movq ${d}, %rdx\n", .{text.len});
            },
            .identifier => {
                const src = self.symbolAt(value.resolved orelse return error.MiscompiledAst);
                if (src.typ != .str) return error.MiscompiledAst;
                try self.print("    movq -{d}(%rbp), %rax\n", .{slotOffset(src.slot)});
                try self.print("    movq -{d}(%rbp), %rdx\n", .{slotOffset(src.slot + 1)});
            },
            .call, .method_call => {
                const ref = (try callRefOf(value)) orelse return error.MiscompiledAst;
                if (self.checked.functions[ref.index].return_type != .str) return error.MiscompiledAst;
                try self.emitCallWith(ref.index, ref.site);
            },
            else => return error.MiscompiledAst,
        }
    }

    fn emitStrStore(self: *FnEmitter, dst: *const sema.Symbol, value: *ast.Expr) Error!void {
        try self.emitStrValue(value);
        try self.print("    movq %rax, -{d}(%rbp)\n", .{slotOffset(dst.slot)});
        try self.print("    movq %rdx, -{d}(%rbp)\n", .{slotOffset(dst.slot + 1)});
    }

    /// `print(s)`: one `write(1, ptr, len)` syscall for the text and another for
    /// the line break. `syscall` requires no stack alignment and clobbers
    /// `%rcx`/`%r11`, which hold no state between expressions in this backend.
    fn emitPrint(self: *FnEmitter, call: ast.Expr.Call) Error!void {
        if (call.args.len != 1) return error.MiscompiledAst;
        const arg = call.args[0];

        // `emitStrValue` leaves the pointer in `%rax` and the length in `%rdx`; `write`
        // expects the pointer in `%rsi` and the length in `%rdx`.
        try self.emitStrValue(arg);
        try self.print("    movq %rax, %rsi\n", .{});

        try self.print("    movl $1, %eax\n", .{}); // syscall write
        try self.print("    movl $1, %edi\n", .{}); // fd = stdout
        try self.print("    syscall\n", .{});
        try self.print("    leaq .Lnl(%rip), %rsi\n", .{});
        try self.print("    movq $1, %rdx\n", .{});
        try self.print("    movl $1, %eax\n", .{});
        try self.print("    movl $1, %edi\n", .{});
        try self.print("    syscall\n", .{});
        self.state.used_print = true;
    }

    /// `print_i32(n)`: evaluates the argument in `%eax`, passes it in `%edi` (SysV)
    /// and calls the shared `kyn_print_i32` routine.
    fn emitPrintI32(self: *FnEmitter, call: ast.Expr.Call) Error!void {
        if (call.args.len != 1) return error.MiscompiledAst;
        try self.emitExpr(call.args[0]);
        try self.print("    movl %eax, %edi\n", .{});
        try self.print("    call kyn_print_i32\n", .{});
        self.state.used_print_i32 = true;
    }

    fn emitBinaryOp(self: *FnEmitter, binary: ast.Expr.Binary) Error!void {
        try self.emitExpr(binary.lhs);
        try self.print("    pushq %rax\n", .{});
        try self.emitExpr(binary.rhs);
        try self.print("    movl %eax, %ecx\n", .{});
        try self.print("    popq %rax\n", .{});

        switch (binary.op) {
            .add => try self.print("    addl %ecx, %eax\n", .{}),
            .sub => try self.print("    subl %ecx, %eax\n", .{}),
            .mul => try self.print("    imull %ecx, %eax\n", .{}),
            .div => {
                try self.print("    cltd\n", .{});
                try self.print("    idivl %ecx\n", .{});
            },
            .mod => {
                try self.print("    cltd\n", .{});
                try self.print("    idivl %ecx\n", .{});
                try self.print("    movl %edx, %eax\n", .{});
            },
            .lt, .le, .gt, .ge, .eq, .ne => {
                try self.print("    cmpl %ecx, %eax\n", .{});
                const setcc: []const u8 = switch (binary.op) {
                    .lt => "setl",
                    .le => "setle",
                    .gt => "setg",
                    .ge => "setge",
                    .eq => "sete",
                    .ne => "setne",
                    else => unreachable,
                };
                try self.print("    {s} %al\n", .{setcc});
                try self.print("    movzbl %al, %eax\n", .{});
            },
            .bitand => try self.print("    andl %ecx, %eax\n", .{}),
            .bitor => try self.print("    orl %ecx, %eax\n", .{}),
            .bitxor => try self.print("    xorl %ecx, %eax\n", .{}),
            .shl => try self.print("    shll %cl, %eax\n", .{}),
            .shr => try self.print("    shrl %cl, %eax\n", .{}),
            .and_op, .or_op => unreachable,
        }
    }

    /// Short-circuit: `&&` only evaluates the right side when the left is true.
    fn emitLogical(self: *FnEmitter, binary: ast.Expr.Binary) Error!void {
        const is_and = binary.op == .and_op; // false => or
        const short_label = try self.label(if (is_and) "and_false" else "or_true");
        const end_label = try self.label(if (is_and) "and_end" else "or_end");

        try self.emitExpr(binary.lhs);
        try self.print("    cmpl $0, %eax\n", .{});
        if (is_and) {
            try self.print("    je {s}\n", .{short_label});
        } else {
            try self.print("    jne {s}\n", .{short_label});
        }

        try self.emitExpr(binary.rhs);
        try self.print("    cmpl $0, %eax\n", .{});
        if (is_and) {
            try self.print("    je {s}\n", .{short_label});
        } else {
            try self.print("    jne {s}\n", .{short_label});
        }

        try self.print("    movl ${d}, %eax\n", .{@as(u8, if (is_and) 1 else 0)});
        try self.print("    jmp {s}\n", .{end_label});
        try self.print("{s}:\n", .{short_label});
        try self.print("    movl ${d}, %eax\n", .{@as(u8, if (is_and) 0 else 1)});
        try self.print("{s}:\n", .{end_label});
    }

    /// Call expression: builtin or free function.
    fn emitCall(self: *FnEmitter, call: ast.Expr.Call) Error!void {
        if (call.builtin) |builtin| switch (builtin) {
            .print => return self.emitPrint(call),
            .print_i32 => return self.emitPrintI32(call),
        };
        try self.emitCallWith(call.callee_fn orelse return error.MiscompiledAst, .{ .list = call.args });
    }

    /// Call by resolved index: `site` carries the receiver of a method first.
    fn emitCallWith(self: *FnEmitter, callee_index: u32, site: codegen.Arguments) Error!void {
        const callee = self.checked.functions[callee_index];
        if (site.count() != callee.params.len) return error.MiscompiledAst;

        // Each argument takes 1 register, 2 when it is `str` (pointer and
        // length, in that order) and one per field when it is a struct. Semantics
        // already validated the total.
        var words: usize = 0;
        for (callee.params, 0..) |ptype, i| {
            const struct_id = if (i < callee.param_struct_ids.len) callee.param_struct_ids[i] else 0;
            words += self.registerWordsOf(ptype, struct_id);
        }
        if (words > arg_registers.len) return error.UnsupportedNode;

        // Fast path: with a single argument nothing can clobber the target
        // registers, so we move directly without going through the stack.
        if (site.count() == 1 and callee.params[0] != .aggregate) {
            if (callee.params[0] == .str) {
                try self.emitStrValue(site.at(0));
                try self.print("    movq %rax, {s}\n", .{arg_registers_64[0]});
                try self.print("    movq %rdx, {s}\n", .{arg_registers_64[1]});
            } else if (callee.params[0] == .enumeration) {
                try self.emitEnumValue(site.at(0));
                try self.print("    movl %eax, {s}\n", .{arg_registers[0]});
                try self.print("    movl %edx, {s}\n", .{arg_registers[1]});
            } else {
                try self.emitExpr(site.at(0));
                try self.print("    movl %eax, {s}\n", .{arg_registers[0]});
            }
            try self.print("    call kyn_{s}\n", .{callee.symbol_name});
            return;
        }

        for (0..site.count()) |arg_index| {
            const arg = site.at(arg_index);
            const ptype = callee.params[arg_index];
            if (ptype == .aggregate) {
                const struct_id = if (arg_index < callee.param_struct_ids.len)
                    callee.param_struct_ids[arg_index]
                else
                    0;
                try self.emitStructArgsPush(struct_id, arg);
            } else if (ptype == .str) {
                try self.emitStrValue(arg);
                try self.print("    pushq %rax\n", .{});
                try self.print("    pushq %rdx\n", .{});
            } else if (ptype == .enumeration) {
                // Tag then payload: the payload pops first, into the higher
                // register index (same pairing as `str`).
                try self.emitEnumValue(arg);
                try self.print("    pushq %rax\n", .{});
                try self.print("    pushq %rdx\n", .{});
            } else {
                try self.emitExpr(arg);
                try self.print("    pushq %rax\n", .{});
            }
        }

        // Pops in reverse order: the last pushed word goes to the highest
        // register index, preserving argument order.
        var word: usize = words;
        while (word > 0) {
            word -= 1;
            try self.print("    popq %rax\n", .{});
            try self.print("    movq %rax, {s}\n", .{arg_registers_64[word]});
        }

        // The stack is back to 16-byte alignment before the call,
        // since every argument was pushed and popped.
        try self.print("    call kyn_{s}\n", .{callee.symbol_name});
    }
};

